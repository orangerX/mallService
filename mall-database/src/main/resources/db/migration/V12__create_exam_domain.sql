) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='考试蓝图部分';

CREATE TABLE exam_paper (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id BIGINT UNSIGNED NOT NULL,
    paper_no VARCHAR(40) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    blueprint_id BIGINT UNSIGNED NOT NULL,
    blueprint_version_snapshot VARCHAR(32) NOT NULL,
    status ENUM('IN_PROGRESS', 'SUBMITTED', 'AUTO_SUBMITTED') NOT NULL DEFAULT 'IN_PROGRESS',
    started_at DATETIME(3) NOT NULL,
    due_at DATETIME(3) NOT NULL,
    submitted_at DATETIME(3) NULL,
    objective_score DECIMAL(6, 2) UNSIGNED NULL,
    translation_self_score TINYINT UNSIGNED NULL,
    writing_self_score TINYINT UNSIGNED NULL,
    self_score_total DECIMAL(6, 2) UNSIGNED NULL,
    version INT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    UNIQUE KEY uk_exam_paper_paper_no (paper_no),
    KEY idx_exam_paper_user_status (user_id, status),
    KEY idx_exam_paper_blueprint (blueprint_id),
    CONSTRAINT fk_exam_paper_user FOREIGN KEY (user_id) REFERENCES sys_user (id),
    CONSTRAINT fk_exam_paper_blueprint FOREIGN KEY (blueprint_id) REFERENCES exam_blueprint (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='考试试卷';

