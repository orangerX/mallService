CREATE TABLE exam_question_source (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    source_name VARCHAR(128) NOT NULL,
    source_type VARCHAR(64) NOT NULL,
    original_url VARCHAR(1024) NULL,
    copyright_status ENUM('ORIGINAL', 'AUTHORIZED', 'PUBLIC_OFFICIAL', 'UNVERIFIED', 'PROHIBITED') NOT NULL,
    review_status ENUM('DRAFT', 'PENDING', 'APPROVED', 'REJECTED', 'DISABLED') NOT NULL DEFAULT 'DRAFT',
    copyright_note TEXT NULL,
    reviewed_by BIGINT UNSIGNED NULL,
    review_comment TEXT NULL,
    reviewed_at DATETIME(3) NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_exam_question_source_review_status (review_status),
    CONSTRAINT fk_exam_question_source_reviewer FOREIGN KEY (reviewed_by) REFERENCES sys_admin (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='考试题源及版权审核';

CREATE TABLE exam_import_batch (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    file_name VARCHAR(255) NOT NULL,
    file_format VARCHAR(32) NOT NULL,
    source_id BIGINT UNSIGNED NOT NULL,
    imported_by BIGINT UNSIGNED NOT NULL,
    status ENUM('UPLOADED', 'VALIDATED', 'IMPORTED', 'REJECTED') NOT NULL DEFAULT 'UPLOADED',
    total_rows INT UNSIGNED NOT NULL DEFAULT 0,
    success_rows INT UNSIGNED NOT NULL DEFAULT 0,
    failed_rows INT UNSIGNED NOT NULL DEFAULT 0,
    structure_errors JSON NULL,
    duplicate_warnings JSON NULL,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_exam_import_batch_source (source_id),
    KEY idx_exam_import_batch_importer_created (imported_by, created_at),
    CONSTRAINT fk_exam_import_batch_source FOREIGN KEY (source_id) REFERENCES exam_question_source (id),
    CONSTRAINT fk_exam_import_batch_importer FOREIGN KEY (imported_by) REFERENCES sys_admin (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='考试题库导入批次';

CREATE TABLE exam_question_group (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    group_type ENUM('DIALOGUE', 'READING') NOT NULL,
    title VARCHAR(255) NOT NULL,
    instruction TEXT NULL,
    content LONGTEXT NOT NULL,
    shared_options JSON NULL,
    source_id BIGINT UNSIGNED NOT NULL,
    difficulty TINYINT UNSIGNED NOT NULL,
    knowledge_points JSON NULL,
    content_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    review_status ENUM('DRAFT', 'PENDING', 'APPROVED', 'REJECTED', 'DISABLED') NOT NULL DEFAULT 'DRAFT',
    enabled TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_exam_question_group_source (source_id),
    KEY idx_exam_question_group_fingerprint (content_fingerprint),
    KEY idx_exam_question_group_available (group_type, review_status, enabled),
    CONSTRAINT fk_exam_question_group_source FOREIGN KEY (source_id) REFERENCES exam_question_source (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='考试题组';

CREATE TABLE exam_question (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    group_id BIGINT UNSIGNED NULL,
    question_type ENUM('DIALOGUE_BLANK', 'READING', 'VOCABULARY', 'GRAMMAR', 'TRANSLATION', 'WRITING') NOT NULL,
    stem LONGTEXT NOT NULL,
    options JSON NULL,
    correct_answer JSON NULL,
    explanation LONGTEXT NULL,
    reference_answer LONGTEXT NULL,
    sample_answer LONGTEXT NULL,
    scoring_rubric JSON NULL,
    source_id BIGINT UNSIGNED NOT NULL,
    group_sort_order INT UNSIGNED NULL,
    difficulty TINYINT UNSIGNED NOT NULL,
    knowledge_points JSON NULL,
    content_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    review_status ENUM('DRAFT', 'PENDING', 'APPROVED', 'REJECTED', 'DISABLED') NOT NULL DEFAULT 'DRAFT',
    enabled TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    PRIMARY KEY (id),
    KEY idx_exam_question_group_order (group_id, group_sort_order),
    KEY idx_exam_question_source (source_id),
    KEY idx_exam_question_fingerprint (content_fingerprint),
    KEY idx_exam_question_available (question_type, review_status, enabled),
    CONSTRAINT fk_exam_question_group FOREIGN KEY (group_id) REFERENCES exam_question_group (id),
    CONSTRAINT fk_exam_question_source FOREIGN KEY (source_id) REFERENCES exam_question_source (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='考试题目';

CREATE TABLE exam_blueprint (
