    KEY idx_exam_wrong_record_question (original_question_id),
    CONSTRAINT fk_exam_wrong_record_user FOREIGN KEY (user_id) REFERENCES sys_user (id),
    CONSTRAINT fk_exam_wrong_record_paper FOREIGN KEY (paper_id) REFERENCES exam_paper (id),
    CONSTRAINT fk_exam_wrong_record_item FOREIGN KEY (paper_item_id) REFERENCES exam_paper_item_snapshot (id),
